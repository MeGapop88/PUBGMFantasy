/**
 * Returns logo info for a team name, or a generated fallback object.
 */
export function getTeamLogoInfo(teamName) {
  if (!teamName) {
    return { logo: null, color: '#FF6B00', short: '?' };
  }

  const name = teamName.trim();
  if (TEAM_LOGOS[name]) {
    return TEAM_LOGOS[name];
  }

  // Fallback lookup case-insensitive
  const key = Object.keys(TEAM_LOGOS).find(k => k.toLowerCase() === name.toLowerCase());
  if (key) {
    return TEAM_LOGOS[key];
  }

  // Generated fallback
  const initials = name.replace(/[^a-zA-Z0-9]/g, '').slice(0, 3).toUpperCase() || 'TM';
  return {
    logo: null,
    color: '#FF6B00',
    short: initials,
  };
}

/**
 * Returns HTML element string for Team Logo Badge
 */
export function renderTeamLogoBadge(teamName, sizeClass = 'w-10 h-10', borderClass = 'border-2 border-primary') {
  const info = getTeamLogoInfo(teamName);

  if (info.logo) {
    return `
      <div class="${sizeClass} rounded-full ${borderClass} overflow-hidden bg-[#0E0E0F] flex-shrink-0 flex items-center justify-center">
        <img src="${info.logo}" alt="${teamName} logo" class="w-full h-full object-cover" onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';" />
        <div class="w-full h-full bg-[#0E0E0F] font-headline font-bold text-xs text-primary flex items-center justify-center" style="display:none">
          ${info.short}
        </div>
      </div>
    `;
  }

  return `
    <div class="${sizeClass} rounded-full ${borderClass} bg-[#0E0E0F] flex-shrink-0 flex items-center justify-center font-headline font-bold text-xs text-primary">
      ${info.short}
    </div>
  `;
}
